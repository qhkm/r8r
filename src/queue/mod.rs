//! Job queue — distribute workflow runs across multiple workers.
//!
//! [`JobQueue`] is a backend-agnostic interface. Two implementations ship:
//!
//! - [`memory::MemoryQueue`] — in-process FIFO queue (default; also used in tests).
//! - [`redis::RedisQueue`] — reliable queue backed by Redis (`--features redis`).
//!   Uses the BRPOPLPUSH pattern (pending list → in-flight list → ack/requeue)
//!   so a crashed worker never silently loses a job.
//!
//! Workers pull [`RunJob`] payloads, load the workflow definition from shared
//! storage (SQLite/PostgreSQL), execute via the engine, then `ack`. The design
//! keeps r8r's at-least-once + idempotency semantics: replaying a job after a
//! crash is safe because executions are keyed by `job_id`.

pub mod memory;
pub mod worker;

#[cfg(feature = "redis")]
pub mod redis;

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use std::time::Duration;

use crate::error::Result;

/// Default maximum age (in seconds) of an in-flight job before a worker
/// considers it stale and moves it back to the pending queue.
///
/// Kept conservative: workflows can legitimately run for minutes.
pub const DEFAULT_STALE_JOB_SECS: u64 = 3600;

/// A unit of work: execute one workflow with a given input.
///
/// The `job_id` doubles as the execution ID, so:
/// - the worker knows the run ID *before* execution starts,
/// - at-least-once replay is idempotent at the storage layer.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RunJob {
    /// Unique job/execution ID. Generated by the enqueuer.
    pub job_id: String,
    /// Workflow ID to execute.
    pub workflow_id: String,
    /// Optional pinned workflow version. Latest is used when `None`.
    pub version: Option<u32>,
    /// Trigger label recorded on the execution (e.g. `"queue"`, `"api"`).
    pub trigger_type: String,
    /// Workflow input payload.
    pub input: serde_json::Value,
    /// Correlation ID for end-to-end tracing.
    pub correlation_id: Option<String>,
    /// Idempotency key — duplicate keys are rejected by the storage layer.
    pub idempotency_key: Option<String>,
    /// Origin identifier (e.g. `"cli"`, `"api"`, `"cron"`).
    pub origin: Option<String>,
    /// When the job was enqueued (UTC).
    pub enqueued_at: DateTime<Utc>,
    /// Number of delivery attempts so far (drives stale requeue decisions).
    pub attempts: u32,
}

impl RunJob {
    /// Create a new job with a fresh timestamp and zero attempts.
    pub fn new(
        job_id: String,
        workflow_id: String,
        version: Option<u32>,
        input: serde_json::Value,
    ) -> Self {
        Self {
            job_id,
            workflow_id,
            version,
            trigger_type: "queue".to_string(),
            input,
            correlation_id: None,
            idempotency_key: None,
            origin: None,
            enqueued_at: Utc::now(),
            attempts: 0,
        }
    }

    /// Builder-style: set trigger type.
    pub fn with_trigger(mut self, trigger_type: impl Into<String>) -> Self {
        self.trigger_type = trigger_type.into();
        self
    }

    /// Builder-style: set correlation ID.
    pub fn with_correlation(mut self, correlation_id: impl Into<String>) -> Self {
        self.correlation_id = Some(correlation_id.into());
        self
    }

    /// Builder-style: set idempotency key.
    pub fn with_idempotency_key(mut self, key: impl Into<String>) -> Self {
        self.idempotency_key = Some(key.into());
        self
    }

    /// Builder-style: set origin.
    pub fn with_origin(mut self, origin: impl Into<String>) -> Self {
        self.origin = Some(origin.into());
        self
    }
}

/// Backend-agnostic job queue interface.
///
/// Implementations must be `Send + Sync` so workers can share them across
/// Tokio tasks.
#[async_trait::async_trait]
pub trait JobQueue: Send + Sync + 'static {
    /// Push a job to the pending queue.
    async fn enqueue(&self, job: RunJob) -> Result<()>;

    /// Pop a job from the pending queue, blocking up to `timeout`.
    ///
    /// Returns `Ok(None)` when the timeout elapses with no job available.
    async fn dequeue(&self, timeout: Duration) -> Result<Option<RunJob>>;

    /// Mark a job as successfully processed (removes it from the in-flight set).
    async fn ack(&self, job: &RunJob) -> Result<()>;

    /// Return a (failed or expired) job to the pending queue for retry.
    async fn requeue(&self, job: &RunJob) -> Result<()>;

    /// Number of jobs currently pending (best-effort; used by `r8r worker --status`).
    async fn pending_len(&self) -> Result<usize>;

    /// Move jobs stuck in the in-flight set older than `max_age` back to pending.
    ///
    /// Used on worker startup and periodically to recover from crashes.
    async fn requeue_stale(&self, max_age: Duration) -> Result<usize>;
}
